/* FCD1: belirlenimci rastgele veri */
function rng(seed) { let x = seed >>> 0 || 1; return () => { x ^= x << 13; x >>>= 0; x ^= x >>> 17; x ^= x << 5; x >>>= 0; return x & 255; }; }
function bytes(n, seed) { const r = rng(seed); const b = Buffer.alloc(n); for (let i = 0; i < n; i++) b[i] = r(); return b; }
const a = bytes(300000, 7);
const b = Buffer.concat([a.subarray(0, 100000), bytes(5000, 9), a.subarray(100000, 250000), a.subarray(260000), Buffer.from('son')]);
const vec = { 'empty-abc': [Buffer.alloc(0), Buffer.from('abc')], 'shift': [a, b], 'same': [a, a], 'to-empty': [Buffer.from('xyz'), Buffer.alloc(0)] };
const fcdOut = {};
const pending = [];
for (const [name, [o, n]] of Object.entries(vec)) {
  pending.push(fcdelta.make(o, n).then((p) => {
    fcdOut[`tests/fixtures/fcd1/${name}.old`] = o;
    fcdOut[`tests/fixtures/fcd1/${name}.new`] = n;
    fcdOut[`tests/fixtures/fcd1/${name}.fcd1`] = p;
  }));
}

Promise.all(pending).then(() => {
  Object.assign(files, fcdOut);
  let stale = 0;
  for (const rel of Object.keys(files).sort()) {
    const f = path.join(ROOT, rel);
    const body = Buffer.isBuffer(files[rel]) ? files[rel] : Buffer.from(files[rel], 'utf8');
    const cur = fs.existsSync(f) ? fs.readFileSync(f) : null;
    if (cur && cur.equals(body)) continue;
    stale++;
    if (check) { console.error('güncel değil: ' + rel); continue; }
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, body);
    console.log('yazıldı: ' + rel + ' (' + body.length + ' bayt, sha256 ' + crypto.createHash('sha256').update(body).digest('hex').slice(0, 12) + ')');
  }
  if (check && stale) { console.error(stale + ' dosya güncel değil — node tools/gen-core.js çalıştırın'); process.exit(1); }
  if (check) console.log('gen-core: hepsi güncel');
});
